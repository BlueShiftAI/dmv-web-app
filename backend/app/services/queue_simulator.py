"""
Queue simulator service.

Generates synthetic queue activity for demo locations:
  - Walk-in arrivals (Poisson-distributed)
  - Service starts (FIFO, capacity-bounded)
  - Service completions (log-normal duration)
  - Occasional document-related delays
  - No-show detection (entries waiting > threshold)

All data is clearly synthetic.  The simulator runs as a one-shot
function called from the seed script or the /api/admin/simulate endpoint.
It does NOT spawn threads; callers decide when to invoke it.

Documented baseline:
  - avg_service_minutes = 12   (measured from prior synthetic runs)
  - arrival_rate_per_hour = 8  (walk-ins at a mid-busy Rock Hill office)
  - active_windows = 3         (teller windows open)
  - delay_probability = 0.15   (15 % of transactions hit a document delay)
  - no_show_threshold_minutes = 30
"""
from __future__ import annotations

import random
import uuid
from datetime import datetime, timedelta, timezone
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from sqlalchemy.orm import Session

# ---------------------------------------------------------------------------
# Simulation parameters (documented baseline)
# ---------------------------------------------------------------------------
DEFAULT_PARAMS = {
    "avg_service_minutes": 12,
    "service_stddev_minutes": 4,       # log-normal spread
    "arrival_rate_per_hour": 8,        # walk-in arrivals
    "active_windows": 3,               # parallel service windows
    "delay_probability": 0.15,         # doc-related delay rate
    "delay_extra_minutes": 8,          # added time when delay occurs
    "no_show_threshold_minutes": 30,   # waiting longer → no-show
    "simulation_hours": 8,             # length of simulated day
    "step_minutes": 5,                 # simulation resolution
}

DISCLAIMER = (
    "Simulated queue data — not real SCDMV operations. "
    "Generated by the DMV Web App demo simulator."
)


def _log_normal_service(avg: float, std: float) -> float:
    """Return a log-normal service duration in minutes (always positive)."""
    import math
    mu = math.log(avg**2 / math.sqrt(avg**2 + std**2))
    sigma = math.sqrt(math.log(1 + (std / avg) ** 2))
    return max(1.0, random.lognormvariate(mu, sigma))


def run_simulation(
    db: "Session",
    location_id: str,
    staff_user_id: str,
    params: dict | None = None,
    reference_time: datetime | None = None,
) -> dict:
    """
    Run a full-day queue simulation for one location.
    Creates QueueEntry and QueueEvent rows in the database.
    Returns a summary dict.

    reference_time: start of the simulated day (defaults to today 08:30 UTC).
    """
    from app.models.models import (
        Case,
        QueueEntry,
        QueueEntryStatus,
        QueueEvent,
        QueueEventType,
        User,
        UserRole,
    )

    p = {**DEFAULT_PARAMS, **(params or {})}
    step = timedelta(minutes=p["step_minutes"])
    now = reference_time or datetime.now(timezone.utc).replace(
        hour=13, minute=30, second=0, microsecond=0
    )
    end = now + timedelta(hours=p["simulation_hours"])

    # Poisson arrival probability per step
    arrival_prob = (p["arrival_rate_per_hour"] / 60) * p["step_minutes"]

    # We need a demo user to attach entries to.  Reuse the staff user.
    staff = db.get(User, staff_user_id)
    if not staff:
        raise ValueError(f"Staff user {staff_user_id!r} not found")

    # Synthetic cases are created on-the-fly (not tied to real users for sim)
    queue: list[dict] = []   # {entry_id, arrived_at, status, case_id}
    in_service: list[dict] = []  # {entry_id, started_at, duration_min, case_id}
    summary = {
        "location_id": location_id,
        "arrivals": 0,
        "completed": 0,
        "no_shows": 0,
        "document_delays": 0,
        "disclaimer": DISCLAIMER,
    }

    t = now
    while t < end:
        # --- Arrivals ---
        if random.random() < arrival_prob:
            # Create a minimal synthetic case (no real user needed for demo)
            case = Case(
                user_id=staff.id,
                location_id=location_id,
                scenario="private_party_purchase",
            )
            db.add(case)
            db.flush()

            entry = QueueEntry(
                case_id=case.id,
                location_id=location_id,
                is_walk_in=True,
                checked_in_at=t,
                status=QueueEntryStatus.waiting,
            )
            db.add(entry)
            db.flush()

            db.add(QueueEvent(
                queue_entry_id=entry.id,
                event_type=QueueEventType.checked_in,
                payload={"simulated": True},
                ts=t,
            ))
            queue.append({"entry_id": entry.id, "arrived_at": t, "case_id": case.id})
            summary["arrivals"] += 1

        # --- No-show detection ---
        threshold = timedelta(minutes=p["no_show_threshold_minutes"])
        still_waiting = []
        for item in queue:
            waited = t - item["arrived_at"]
            if waited > threshold and random.random() < 0.3:
                entry = db.get(QueueEntry, item["entry_id"])
                if entry and entry.status == QueueEntryStatus.waiting:
                    entry.status = QueueEntryStatus.no_show
                    entry.no_show_at = t
                    db.add(QueueEvent(
                        queue_entry_id=entry.id,
                        event_type=QueueEventType.no_show,
                        payload={"simulated": True, "waited_minutes": int(waited.total_seconds() / 60)},
                        ts=t,
                    ))
                    summary["no_shows"] += 1
            else:
                still_waiting.append(item)
        queue = still_waiting

        # --- Service completions ---
        finished = []
        for srv in in_service:
            elapsed = (t - srv["started_at"]).total_seconds() / 60
            if elapsed >= srv["duration_min"]:
                entry = db.get(QueueEntry, srv["entry_id"])
                if entry:
                    entry.status = QueueEntryStatus.completed
                    entry.service_completed_at = t
                    db.add(QueueEvent(
                        queue_entry_id=entry.id,
                        event_type=QueueEventType.service_completed,
                        payload={"simulated": True, "duration_minutes": round(elapsed, 1)},
                        ts=t,
                    ))
                summary["completed"] += 1
            else:
                finished.append(srv)
        in_service = [s for s in in_service if s not in finished]

        # --- Start new service (fill free windows) ---
        free_windows = p["active_windows"] - len(in_service)
        while free_windows > 0 and queue:
            item = queue.pop(0)
            entry = db.get(QueueEntry, item["entry_id"])
            if not entry or entry.status != QueueEntryStatus.waiting:
                continue

            # Call
            entry.status = QueueEntryStatus.called
            entry.called_at = t
            entry.staff_id = staff.id
            db.add(QueueEvent(
                queue_entry_id=entry.id,
                event_type=QueueEventType.called,
                payload={"simulated": True},
                ts=t,
            ))

            # Document delay?
            has_delay = random.random() < p["delay_probability"]
            if has_delay:
                db.add(QueueEvent(
                    queue_entry_id=entry.id,
                    event_type=QueueEventType.document_delay,
                    payload={"simulated": True, "extra_minutes": p["delay_extra_minutes"]},
                    ts=t,
                ))
                summary["document_delays"] += 1

            # Start service
            entry.status = QueueEntryStatus.in_service
            entry.service_started_at = t
            db.add(QueueEvent(
                queue_entry_id=entry.id,
                event_type=QueueEventType.service_started,
                payload={"simulated": True},
                ts=t,
            ))

            dur = _log_normal_service(p["avg_service_minutes"], p["service_stddev_minutes"])
            if has_delay:
                dur += p["delay_extra_minutes"]

            in_service.append({
                "entry_id": entry.id,
                "started_at": t,
                "duration_min": dur,
                "case_id": item["case_id"],
            })
            free_windows -= 1

        t += step

    db.commit()
    return summary


# ---------------------------------------------------------------------------
# Wait estimator — uses real event log when available
# ---------------------------------------------------------------------------

def estimate_wait_from_history(
    db: "Session",
    location_id: str,
    waiting_count: int,
    in_service_count: int,
    lookback_hours: int = 2,
) -> dict:
    """
    Estimate wait time using recent completed queue entries.

    Returns:
        {
            estimated_wait_minutes: int | None,
            p50_service_minutes: float | None,
            p90_service_minutes: float | None,
            sample_size: int,
            method: str,
        }
    """
    from app.models.models import QueueEntry, QueueEntryStatus

    since = datetime.now(timezone.utc) - timedelta(hours=lookback_hours)
    completed = (
        db.query(QueueEntry)
        .filter(
            QueueEntry.location_id == location_id,
            QueueEntry.status == QueueEntryStatus.completed,
            QueueEntry.service_completed_at >= since,
            QueueEntry.service_started_at.isnot(None),
            QueueEntry.checked_in_at.isnot(None),
        )
        .all()
    )

    if not completed:
        # Fall back to documented baseline
        from app.services.queue_service import estimate_wait
        return {
            "estimated_wait_minutes": estimate_wait(waiting_count, in_service_count),
            "p50_service_minutes": None,
            "p90_service_minutes": None,
            "sample_size": 0,
            "method": "baseline_formula",
        }

    # Service durations (started → completed)
    durations = sorted(
        [
            (e.service_completed_at - e.service_started_at).total_seconds() / 60
            for e in completed
            if e.service_completed_at and e.service_started_at
        ]
    )
    n = len(durations)
    p50 = durations[int(n * 0.50)] if n else None
    p90 = durations[min(int(n * 0.90), n - 1)] if n else None

    avg_service = sum(durations) / n if n else DEFAULT_PARAMS["avg_service_minutes"]
    active = max(in_service_count, 1)
    wait = max(0, round((waiting_count / active) * avg_service)) if waiting_count > 0 else 0

    return {
        "estimated_wait_minutes": wait,
        "p50_service_minutes": round(p50, 1) if p50 else None,
        "p90_service_minutes": round(p90, 1) if p90 else None,
        "sample_size": n,
        "method": "event_log_history",
    }
